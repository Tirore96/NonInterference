#!/usr/bin/env python3
"""Generate mechlinks.tex: for every name defined in ../theories/*.v, the file and
line it is defined on.  The paper links to the mechanisation with \\m{name}, which
looks the name up in this table, so line numbers never have to be maintained by
hand.  Run automatically by latexmk (see .latexmkrc).

Names defined in more than one file resolve to the first file in FILES order; the
script reports them so a link never silently points at the wrong definition.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
THEORIES = os.path.join(HERE, '..', 'theories')
FILES = ['definitions.v', 'theorems.v', 'models.v', 'noninterference.v', 'adequacy.v']
KEYWORDS = ('Lemma', 'Theorem', 'Corollary', 'Definition', 'Fixpoint',
            'CoFixpoint', 'Inductive', 'CoInductive', 'Variant', 'Record',
            'Class', 'Instance')
DEF = re.compile(r'^\s*(?:Local\s+|Global\s+|#\[[^\]]*\]\s*)*(?:%s)\s+([A-Za-z_][\w\']*)'
                 % '|'.join(KEYWORDS))


def main():
    found = {}
    dups = []
    for f in FILES:
        path = os.path.join(THEORIES, f)
        with open(path, encoding='utf-8') as fh:
            for n, line in enumerate(fh, 1):
                m = DEF.match(line)
                if not m:
                    continue
                name = m.group(1)
                if name in found:
                    dups.append((name, found[name], (f, n)))
                    continue
                found[name] = (f, n)
    out = os.path.join(HERE, 'mechlinks.tex')
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('% Generated by mechlinks.py from ../theories/*.v.  Do not edit.\n')
        for name, (f, n) in sorted(found.items()):
            fh.write('\\mechdef{%s}{theories/%s}{%d}\n' % (name, f, n))
    print('mechlinks: %d names from %d files' % (len(found), len(FILES)))
    for name, (f1, n1), (f2, n2) in dups:
        print('mechlinks: %s defined in %s:%d and %s:%d; linking the first'
              % (name, f1, n1, f2, n2), file=sys.stderr)


if __name__ == '__main__':
    main()
